export function talukasForDistrict(districtName) {
  const key = String(districtName || "").trim();
  const district = GUJARAT_DISTRICTS.find(
    (item) => item.nameGu === key || item.nameEn === key || item.nameHi === key || item.name === key
  );
  return (district?.talukas || []).map((t) => (typeof t === "string" ? t : t.nameGu));
}

export function findDistrict(districtName) {
  const key = String(districtName || "").trim();
  return (
    GUJARAT_DISTRICTS.find(
      (item) => item.nameGu === key || item.nameEn === key || item.nameHi === key || item.name === key
    ) || null
  );
}
