function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => params[key] ?? `{${key}}`);
}

export function getStoredLanguage() {
  const saved = storage.get(STORAGE_KEYS.languagePreference, DEFAULT_LANGUAGE);
  return TRANSLATIONS[saved] ? saved : DEFAULT_LANGUAGE;
}

export function getLanguageMeta(language) {
  return LANGUAGE_META[language] || LANGUAGE_META[DEFAULT_LANGUAGE];
}

export function getAppName(language) {
  return APP_NAMES[language] || APP_NAMES[DEFAULT_LANGUAGE];
}

export function translate(language, key, params) {
  const dict = TRANSLATIONS[language] || TRANSLATIONS[DEFAULT_LANGUAGE];
  const fallback = TRANSLATIONS[DEFAULT_LANGUAGE];
  const value = dict[key] ?? fallback[key] ?? key;
  return typeof value === "string" ? interpolate(value, params) : value;
}

export function translateCurrent(key, params) {
  return translate(getStoredLanguage(), key, params);
}

export function useI18n() {
  const language = useLanguageStore((state) => state.language);
  return useMemo(
    () => ({
      language,
      appName: getAppName(language),
      t: (key, params) => translate(language, key, params),
      meta: getLanguageMeta(language),
    }),
    [language]
  );
}
