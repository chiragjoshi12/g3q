export function normalizeDepartmentAlias(value) {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9\u0A80-\u0AFF]+/g, '');
}

const EXACT_ALIAS_MAP = new Map(
  DEPARTMENTS.flatMap((department) =>
    [department.key, department.nameEn, department.nameGu, ...(department.aliases || [])].map((alias) => [
      normalizeDepartmentAlias(alias),
      department,
    ])
  )
);

export function resolveDepartment(rawValue) {
  const normalized = normalizeDepartmentAlias(rawValue);
  if (!normalized) return DEPARTMENTS[0];

  const exact = EXACT_ALIAS_MAP.get(normalized);
  if (exact) return exact;

  if (/^gk\d*$/.test(normalized) || normalized.includes('generalknowledge')) {
    return DEPARTMENTS[0];
  }
  if (normalized.includes('education') && normalized.includes('summit')) {
    return DEPARTMENTS[1];
  }
  if (normalized.includes('science') || normalized.includes('tech')) {
    return DEPARTMENTS[2];
  }
  if (normalized.includes('constitution') || normalized.includes('legal') || normalized.includes('parliament') || normalized.includes('legisl')) {
    return DEPARTMENTS[3];
  }
  if (normalized.includes('home')) {
    return DEPARTMENTS[4];
  }
  if (normalized.includes('history') || normalized.includes('culture') || normalized.includes('itihas')) {
    return DEPARTMENTS[5];
  }
  if (normalized.includes('finance') || normalized.includes('economic')) {
    return DEPARTMENTS[6];
  }
  if (normalized.includes('civilsuppl') || normalized.includes('food')) {
    return DEPARTMENTS[7];
  }
  if (normalized.includes('forest') || normalized.includes('climate') || normalized.includes('environment')) {
    return DEPARTMENTS[8];
  }
  if (normalized.includes('energy') || normalized.includes('petro')) {
    return DEPARTMENTS[9];
  }
  if (normalized.includes('labour') || normalized.includes('industry') || normalized.includes('kutir')) {
    return DEPARTMENTS[10];
  }
  if (normalized.includes('socialjustice')) {
    return DEPARTMENTS[11];
  }
  if (normalized.includes('women') || normalized.includes('child')) {
    return DEPARTMENTS[12];
  }
  if (normalized.includes('revenue') || normalized.includes('મહેસ')) {
    return DEPARTMENTS[13];
  }
  if (normalized.includes('rural') || normalized.includes('urban') || normalized.includes('panchayat')) {
    return DEPARTMENTS[14];
  }
  if (normalized.includes('narmada') || normalized.includes('waterresources')) {
    return DEPARTMENTS[15];
  }
  if (normalized.includes('transport') || normalized.includes('road') || normalized.includes('port')) {
    return DEPARTMENTS[16];
  }
  if (normalized.includes('sanskrit') || normalized.includes('mothertongue') || normalized.includes('matrubhasha')) {
    return DEPARTMENTS[17];
  }
  if (normalized.includes('tribal')) {
    return DEPARTMENTS[18];
  }
  if (normalized.includes('youth') || normalized.includes('sport')) {
    return DEPARTMENTS[19];
  }
  if (normalized.includes('digital') || normalized.includes('computer')) {
    return DEPARTMENTS[20];
  }
  if (normalized.includes('biology')) {
    return DEPARTMENTS[21];
  }
  if (normalized.includes('chemistry')) {
    return DEPARTMENTS[22];
  }
  if (normalized.includes('physics')) {
    return DEPARTMENTS[23];
  }
  if (normalized.includes('mathematics')) {
    return DEPARTMENTS[24];
  }
  if (normalized.includes('psychology') || normalized.includes('sociology')) {
    return DEPARTMENTS[25];
  }
  if (normalized.includes('logicalreasoning')) {
    return DEPARTMENTS[26];
  }
  if (normalized.includes('agriculture') || normalized.includes('krushi')) {
    return DEPARTMENTS[27];
  }
  if (normalized.includes('geography')) {
    return DEPARTMENTS[28];
  }
  if (normalized.includes('health')) {
    return DEPARTMENTS[29];
  }
  if (normalized.includes('defence')) {
    return DEPARTMENTS[30];
  }
  if (normalized.includes('mineral')) {
    return DEPARTMENTS[31];
  }
  if (normalized.includes('yatradham') || normalized.includes('pilgrimage')) {
    return DEPARTMENTS[32];
  }
  if (normalized.includes('yojana') || normalized.includes('scheme')) {
    return DEPARTMENTS[33];
  }

  return null;
}
